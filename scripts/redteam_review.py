"""Writes redteam/REVIEW.md: every red-team case with both AI labels and our decision, for human review.

    python scripts/redteam_review.py
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from gatekeeper import reader, rules  # noqa: E402

DECISIONS = ("REJECT", "APPROVE_STATISTICAL", "APPROVE_SPE")
SETS = (("disputed", "Disputed: the two AIs disagree, a human decides"),
        ("tuning", "Agreed (tuning set): please spot-check"),
        ("holdout", "Agreed (holdout exam set): please spot-check"))


def clean(text):
    return " ".join(str(text).replace("\u2014", "-").replace("\u2013", "-").split())


def case_md(req):
    result = rules.decide(req, reader.read(req))
    review = " (flags staff review)" if result["needs_staff_review"] else ""
    lines = [
        f"### {req['id']}",
        "",
        f"- **Applicant:** {clean(req['applicant'].get('organisation', ''))} ({req['applicant'].get('country', '')})",
        f"- **Requested as:** {req['requested_as']}",
        f"- **Purpose:** {clean(req['purpose'])}",
        f"- **Question:** {clean(req['question'])}",
        f"- **Writer AI:** `{req['intended']['decision']}` - {clean(req['intended'].get('why', ''))}",
        f"- **Judge AI:** `{req['judge']['decision']}` - {clean(req['judge'].get('why', ''))}",
        f"- **Our gatekeeper:** `{result['decision']}`, Art. {', '.join(result['articles'])}{review}",
    ]
    if "expected" in req:
        lines.append(f"- **Label used for scoring:** `{req['expected']}`")
    lines += ["", "Human verdict (tick one):", ""]
    lines += [f"- [ ] {d}" for d in DECISIONS]
    lines += ["", "Note:", "", "---", ""]
    return lines


def main():
    out = ["# Red-team test cases for review", "",
           "Generated by `python scripts/redteam_review.py` from the JSON files in this folder.",
           "The writer AI made each request up with the decision it intended; the judge AI labelled it on its own.",
           "Tick the decision you think is right. Disputed cases only enter a test set once a human has decided.", ""]
    for name, title in SETS:
        paths = sorted((REPO / "redteam" / name).glob("*.json"))
        if not paths:
            continue
        out += [f"## {title} ({len(paths)})", ""]
        for path in paths:
            out += case_md(json.loads(path.read_text(encoding="utf-8")))
    target = REPO / "redteam" / "REVIEW.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target.relative_to(REPO)}")


if __name__ == "__main__":
    main()
